package com.example.ai.domain

import com.example.ai.data.model.ChatMessage

enum class AiOperation(
    val id: String,
    val titlePersian: String,
    val iconEmoji: String,
    val description: String
) {
    GRAMMAR_CORRECTION(
        id = "grammar",
        titlePersian = "اصلاح متن",
        iconEmoji = "✨",
        description = "اصلاح غلط‌های املایی، دستور زبان، نیم‌فاصله‌ها و علائم نگارشی"
    ),
    REWRITE(
        id = "rewrite",
        titlePersian = "بازنویسی",
        iconEmoji = "✍️",
        description = "بازنویسی روان و شیوا با حفظ کامل معنای متن"
    ),
    FORMAL_TONE(
        id = "formal",
        titlePersian = "رسمی کردن",
        iconEmoji = "👔",
        description = "تبدیل متن به لحن رسمی، اداری و محترمانه"
    ),
    FRIENDLY_TONE(
        id = "friendly",
        titlePersian = "دوستانه کردن",
        iconEmoji = "😊",
        description = "تبدیل متن به لحن صمیمی، خودمانی و دلنشین"
    ),
    SHORTEN(
        id = "shorten",
        titlePersian = "کوتاه کردن",
        iconEmoji = "📌",
        description = "خلاصه‌سازی متن با حفظ نکات کلیدی و مفهوم اصلی"
    ),
    EXPAND(
        id = "expand",
        titlePersian = "کامل کردن",
        iconEmoji = "📝",
        description = "گسترش و تکمیل جملات برای توضیح بهتر و زیباتر"
    ),
    TRANSLATE(
        id = "translate",
        titlePersian = "ترجمه",
        iconEmoji = "🌐",
        description = "ترجمه دقیق و روان میان فارسی و انگلیسی"
    ),
    SUGGEST_REPLIES(
        id = "replies",
        titlePersian = "پاسخ پیشنهادی",
        iconEmoji = "💬",
        description = "تولید چند پاسخ آماده هوشمند متناسب با پیام دریافتی"
    ),
    CUSTOM_PROMPT(
        id = "custom",
        titlePersian = "دستور دلخواه",
        iconEmoji = "🤖",
        description = "اجرای درخواست و دستور دلخواه شما روی متن"
    );

    fun buildMessages(userText: String, customInstruction: String? = null, targetLanguage: String = "en"): List<ChatMessage> {
        val systemPrompt = when (this) {
            GRAMMAR_CORRECTION -> """
                شما دستیار هوشمند اصلاح و ویرایش زبان فارسی در کیبورد مرسانا هستید.
                وظیفه شما:
                ۱. اصلاح تمام غلط‌های املایی و نگارشی متن کاربر.
                ۲. رعایت دقیق نیم‌فاصله‌ها (مثلاً «می‌روم»، «خانه‌ها»، «دست‌خوش»).
                ۳. استفاده صحیح از علائم نگارشی فارسی (، ؛ ؟ ! . « »).
                ۴. عدم افزودن هرگونه توضیح اضافی، سلام، یا متن جانبی. فقط متن نهایی اصلاح‌شده را به عنوان خروجی ارسال کنید.
            """.trimIndent()

            REWRITE -> """
                شما دستیار هوشمند بازنویسی فارسی در کیبورد مرسانا هستید.
                وظیفه شما:
                ۱. بازنویسی متن کاربر به صورت روان، شیوا، جذاب و بدون دست‌خوردن مفهوم اصلی.
                ۲. رعایت دقیق نیم‌فاصله‌ها و قواعد ویرایش نگارشی فارسی.
                ۳. عدم افزودن هرگونه مقدمه یا موخره. فقط متن بازنویسی‌شده را ارسال کنید.
            """.trimIndent()

            FORMAL_TONE -> """
                شما دستیار هوشمند نگارش متون رسمی و اداری در کیبورد مرسانا هستید.
                وظیفه شما:
                ۱. تبدیل متن کاربر به لحنی کاملاً رسمی، محترمانه، اداری و حرفه‌ای.
                ۲. رعایت اصول مکاتبات استاندارد و نیم‌فاصله‌های فارسی.
                ۳. فقط متن رسمی‌شده را بدون هیچ توضیح اضافی ارسال کنید.
            """.trimIndent()

            FRIENDLY_TONE -> """
                شما دستیار هوشمند لحن دوستانه در کیبورد مرسانا هستید.
                وظیفه شما:
                ۱. تبدیل متن کاربر به لحنی صمیمی، دوستانه، خودمانی، طبیعی و دلنشین.
                ۲. رعایت قواعد و نیم‌فاصله‌ها در نگارش محاوره‌ای استاندارد فارسی.
                ۳. فقط متن خروجی را بدون توضیح اضافه بازگردانید.
            """.trimIndent()

            SHORTEN -> """
                شما دستیار خلاصه‌سازی و کوتاه‌کردن پیام در کیبورد مرسانا هستید.
                وظیفه شما:
                ۱. کوتاه و فشرده کردن متن با حفظ حداکثری پیام و مفهوم اصلی.
                ۲. حذف زوائد و کلمات تکراری.
                ۳. فقط متن خلاصه‌شده را بدون توضیح برگردانید.
            """.trimIndent()

            EXPAND -> """
                شما دستیار تکمیل و گسترش متن در کیبورد مرسانا هستید.
                وظیفه شما:
                ۱. تکمیل جملات و بسط دادن متن کوتاه کاربر با عبارات زیبا، دقیق و مرتبط با موضوع.
                ۲. رعایت لحن و سیاق متن ورودی.
                ۳. فقط متن کامل‌شده را بازگردانید.
            """.trimIndent()

            TRANSLATE -> """
                شما مترجم هوشمند و دقیق کیبورد مرسانا هستید.
                وظیفه شما:
                - اگر متن ورودی فارسی است، آن را به انگلیسی روان و طبیعی ترجمه کنید.
                - اگر متن ورودی انگلیسی یا زبان دیگری است، آن را به فارسی روان و سلیس ترجمه کنید.
                - از ترجمه تحت‌اللفظی و نامفهوم خودداری کنید.
                - فقط ترجمه نهایی را بدون هیچ کلمه اضافه‌ای ارسال کنید.
            """.trimIndent()

            SUGGEST_REPLIES -> """
                شما دستیار پیشنهاد پاسخ هوشمند کیبورد مرسانا هستید.
                وظیفه شما:
                متن دریافتی کاربر یک پیام یا سوال است. برای این پیام دقیقا ۳ گزینه پاسخ کوتاه، مناسب و متنوع (مثلاً یک پاسخ مثبت، یک پاسخ منفی یا مشروط، یک پاسخ تشکر یا اداری) تولید کنید.
                فرمت خروجی باید به صورت گزینه‌های تفکیک‌شده با خط جدید باشد، به صورت:
                ۱. [گزینه اول]
                ۲. [گزینه دوم]
                ۳. [گزینه سوم]
                هیچ متن توضیحی دیگری ننویسید.
            """.trimIndent()

            CUSTOM_PROMPT -> """
                شما دستیار هوش مصنوعی چندمنظوره در کیبورد فارسی مرسانا هستید.
                دستور کاربر را با دقت روی متن اعمال کنید و خروجی را به صورت تمیز و بدون حاشیه ارائه دهید.
            """.trimIndent()
        }

        val userPromptContent = if (this == CUSTOM_PROMPT && !customInstruction.isNullOrBlank()) {
            "دستور: $customInstruction\n\nمتن ورودی:\n$userText"
        } else {
            userText
        }

        return listOf(
            ChatMessage(role = "system", content = systemPrompt),
            ChatMessage(role = "user", content = userPromptContent)
        )
    }
}
